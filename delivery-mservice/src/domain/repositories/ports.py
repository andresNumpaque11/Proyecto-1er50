from abc import ABC, abstractmethod
from datetime import datetime
from ..shared.ids import OrderId, RouteId, DriverId


class DeliveryOrderRepository(ABC):
    @abstractmethod
    def get(self, id: OrderId): ...
    @abstractmethod
    def exists(self, id: OrderId): ...
    @abstractmethod
    def save(self, entity): ...
class RouteRepository(ABC):
    @abstractmethod
    def get(self, id: RouteId): ...
    @abstractmethod
    def save(self, entity): ...
    @abstractmethod
    def find_open_by_city(self, city): ...
    @abstractmethod
    def find_ready(self): ...
    @abstractmethod
    def find_expired(self, now: datetime): ...
class DriverRepository(ABC):
    @abstractmethod
    def get(self, id: DriverId): ...
    @abstractmethod
    def save(self, entity): ...
    @abstractmethod
    def available(self): ...
class OutboxRepository(ABC):
    @abstractmethod
    def add(self, event): ...
    @abstractmethod
    def pending(self, limit): ...
    @abstractmethod
    def published(self, event_id): ...
    @abstractmethod
    def failed(self, event_id, error): ...
